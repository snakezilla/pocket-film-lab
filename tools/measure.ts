/**
 * Measure tone, colour, grain and speed of each engine on synthetic inputs.
 * Writes measurements/REPORT.md. Run: npx vite-node tools/measure.ts
 * No Chromagraph reference images are used (none are available legally here).
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { renderFilmPixels, type Recipe } from '../src/engine/film'
import { parseLut, type Lut3D } from '../src/engine/lut'
import { srgbDecode } from '../src/engine/color'
import { renderStarterPixels } from './starter'

type Engine = { name: string; run: (px: Uint8ClampedArray, w: number, h: number, r: Recipe) => Uint8ClampedArray }
const lut = (id: string): Lut3D => {
  const b = readFileSync(`public/luts/${id}.bin`)
  return parseLut(b.buffer.slice(b.byteOffset, b.byteOffset + b.byteLength), 33)
}
const engines: Engine[] = [
  { name: 'Starter (original prototype)', run: renderStarterPixels },
  ...['print', 'portra'].map((id) => {
    const l = lut(id)
    return { name: `New: ${id}`, run: (px: Uint8ClampedArray, w: number, h: number, r: Recipe) => renderFilmPixels({ pixels: px, width: w, height: h, recipe: r, lut: l }) }
  }),
]
const CLEAN: Recipe = { strength: 1, grain: 0, halo: 0, exposure: 0 }

const solid = (n: number, rgb: number[]) => {
  const px = new Uint8ClampedArray(n * n * 4)
  for (let i = 0; i < px.length; i += 4) px.set([rgb[0], rgb[1], rgb[2], 255], i)
  return px
}
const centre = (px: Uint8ClampedArray, n: number) => Array.from(px.slice(((n >> 1) * n + (n >> 1)) * 4, ((n >> 1) * n + (n >> 1)) * 4 + 3))

// OKLab for hue/chroma/lightness deltas.
function oklab([r, g, b]: number[]): number[] {
  const [R, G, B] = [r, g, b].map((v) => srgbDecode(v / 255))
  const l = Math.cbrt(0.4122214708 * R + 0.5363325363 * G + 0.0514459929 * B)
  const m = Math.cbrt(0.2119034982 * R + 0.6806995451 * G + 0.1073969566 * B)
  const s = Math.cbrt(0.0883024619 * R + 0.2817188376 * G + 0.6299787005 * B)
  return [0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s, 1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s, 0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s]
}
const lch = (rgb: number[]) => {
  const [L, a, b] = oklab(rgb)
  return { L, C: Math.hypot(a, b), h: ((Math.atan2(b, a) * 180) / Math.PI + 360) % 360 }
}

const lines: string[] = ['# Measurements (synthetic inputs, generated by tools/measure.ts)', '', `Generated ${new Date().toISOString()}. Node ${process.version} on this Mac; iPhone timings are NOT measured here.`, '']

lines.push('## Tone: grey input code -> output code (R,G,B), strength 100%, no grain/halation', '')
const greys = [0, 16, 32, 64, 96, 118, 160, 200, 230, 255]
lines.push(`| Engine | ${greys.join(' | ')} |`, `|---|${greys.map(() => '---').join('|')}|`)
for (const e of engines) {
  const cells = greys.map((g) => centre(e.run(solid(8, [g, g, g]), 8, 8, CLEAN), 8).join(','))
  lines.push(`| ${e.name} | ${cells.join(' | ')} |`)
}

lines.push('', '## Colour: OKLab lightness / chroma / hue change per patch', '', 'dL and dC in OKLab units x100, dh in degrees.', '')
const patches: [string, number[]][] = [['skin', [224, 172, 140]], ['dark skin', [140, 95, 75]], ['sky', [110, 160, 220]], ['foliage', [80, 120, 60]], ['red', [200, 40, 40]], ['yellow', [230, 200, 60]], ['blue', [40, 60, 180]], ['cyan', [60, 180, 190]]]
lines.push(`| Engine | ${patches.map((p) => p[0]).join(' | ')} |`, `|---|${patches.map(() => '---').join('|')}|`)
for (const e of engines) {
  const cells = patches.map(([, rgb]) => {
    const a = lch(rgb)
    const b = lch(centre(e.run(solid(8, rgb as number[]), 8, 8, CLEAN), 8))
    let dh = b.h - a.h
    if (dh > 180) dh -= 360
    if (dh < -180) dh += 360
    return `${((b.L - a.L) * 100).toFixed(1)} / ${((b.C - a.C) * 100).toFixed(1)} / ${dh.toFixed(0)}`
  })
  lines.push(`| ${e.name} | ${cells.join(' | ')} |`)
}

lines.push('', '## Grain: std-dev of output green code at grain 100% (128 px patch)', '')
lines.push('| Engine | code 10 | code 118 | code 240 | lag-1 autocorrelation @118 |', '|---|---|---|---|---|')
for (const e of engines) {
  const n = 128
  const row: string[] = []
  let ac = 0
  for (const g of [10, 118, 240]) {
    const base = e.run(solid(n, [g, g, g]), n, n, CLEAN)
    const out = e.run(solid(n, [g, g, g]), n, n, { ...CLEAN, grain: 1 })
    const d: number[] = []
    for (let i = 1; i < out.length; i += 4) d.push(out[i] - base[i])
    const mean = d.reduce((x, y) => x + y, 0) / d.length
    const v = d.reduce((x, y) => x + (y - mean) ** 2, 0) / d.length
    row.push(Math.sqrt(v).toFixed(2))
    if (g === 118) {
      let c = 0
      for (let i = 0; i < d.length - 1; i++) if ((i + 1) % n) c += (d[i] - mean) * (d[i + 1] - mean)
      ac = c / (d.length - n) / v
    }
  }
  lines.push(`| ${e.name} | ${row.join(' | ')} | ${ac.toFixed(2)} |`)
}

lines.push('', '## Halation: red/blue lift next to a white disc (r=1% of width) on grey 40, halation 100%', '')
lines.push('| Engine | +1% width: dR / dB | +3%: dR / dB | +8%: dR / dB |', '|---|---|---|---|')
{
  const w = 1200, h = 800, cx = 600, cy = 400, rad = 12
  const px = new Uint8ClampedArray(w * h * 4)
  for (let y = 0; y < h; y++) for (let x = 0; x < w; x++) {
    const v = (x - cx) ** 2 + (y - cy) ** 2 < rad * rad ? 255 : 40
    px.set([v, v, v, 255], (y * w + x) * 4)
  }
  for (const e of engines) {
    const off = e.run(px, w, h, CLEAN)
    const on = e.run(px, w, h, { ...CLEAN, halo: 1 })
    const cells = [0.01, 0.03, 0.08].map((f) => {
      const i = (cy * w + cx + rad + Math.round(f * w)) * 4
      return `${on[i] - off[i]} / ${on[i + 2] - off[i + 2]}`
    })
    lines.push(`| ${e.name} | ${cells.join(' | ')} |`)
  }
}

lines.push('', 'Speed: see measurements/SPEED.md (timed in real browsers by tools/speed-browser.mjs; Node timings here are distorted by vite-node module wrapping).')
writeFileSync('measurements/REPORT.md', lines.join('\n') + '\n')
console.log(lines.join('\n'))
